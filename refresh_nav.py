"""Re-renders just the <nav class="sitenav"> block in every already-committed
page, in place, from dashboard_template.py's current render_nav() output.

Needed whenever NAV_SCREENER_LINKS/NAV_INDEX_LINKS/NAV_OPTIONS_LINKS/
NAV_TOOLS_LINKS changes (e.g. a new page added to the nav) - every page that
was generated BEFORE that change has the old nav baked into its committed
HTML, and check_nav.py will fail the next deploy for every one of them, not
just the new page, until each is regenerated. Re-running every page's own
builder script would work too, but several of those re-scan live data
(minutes to tens of minutes) just to pick up a nav-only change - this does
the same substitution deploy_site.py/check_nav.py already treat as the
canonical nav, without touching anything else on the page.

A page's active_href is just its own filename - every call site in this
repo (dashboard_template.render(), render_nav() itself) already follows that
convention, so there's no separate mapping to maintain here.

Skips index.html (regenerated by build_site_index.py, not this) and any
page with no <nav class="sitenav"> block at all (e.g. the nav-less
timing-the-carts.html easter egg, or morning-brief.html by design).

Usage:
    python3 refresh_nav.py                 # every *.html in the repo root
    python3 refresh_nav.py foo.html bar.html
"""
import glob
import re
import sys

from dashboard_template import render_nav

NAV_RE = re.compile(r'<nav class="sitenav">.*?</nav>\n?', re.S)
SKIP = {"index.html"}


def refresh_file(path):
    with open(path, encoding="utf-8") as f:
        content = f.read()

    if not NAV_RE.search(content):
        return None  # no nav on this page - intentional, leave it alone

    new_nav = render_nav(path) + "\n"
    new_content = NAV_RE.sub(lambda m: new_nav, content, count=1)
    if new_content == content:
        return False  # already current

    with open(path, "w", encoding="utf-8") as f:
        f.write(new_content)
    return True


def main():
    files = sys.argv[1:] or sorted(glob.glob("*.html"))
    files = [f for f in files if f not in SKIP]

    changed, unchanged, skipped = [], [], []
    for path in files:
        result = refresh_file(path)
        if result is None:
            skipped.append(path)
        elif result:
            changed.append(path)
        else:
            unchanged.append(path)

    print(f"Refreshed nav in {len(changed)} file(s): {', '.join(changed) if changed else '(none)'}")
    print(f"Already current: {len(unchanged)}. Skipped (no nav): {len(skipped)}.")


if __name__ == "__main__":
    main()
